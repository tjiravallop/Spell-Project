function pixelArt(width, height, colors, paint, { grandScale, lift = 0 }) {
  const pixels = Array.from({ length: height }, () => Array(width).fill(null));

  function rect(color, x, y, w, h) {
    for (let row = Math.max(0, y); row < Math.min(height, y + h); row++) {
      pixels[row].fill(color, Math.max(0, x), Math.min(width, x + w));
    }
  }

  function polygon(color, ...points) {
    for (let y = 0; y < height; y++) {
      const intersections = [];
      for (let i = 0; i < points.length; i++) {
        const [ax, ay] = points[i];
        const [bx, by] = points[(i + 1) % points.length];
        const mid = y + 0.5;
        if ((ay > mid) !== (by > mid)) intersections.push(ax + (mid - ay) * (bx - ax) / (by - ay));
      }
      intersections.sort((a, b) => a - b);
      for (let i = 0; i + 1 < intersections.length; i += 2) {
        const left = Math.ceil(intersections[i] - 0.5);
        rect(color, left, y, Math.ceil(intersections[i + 1] - 0.5) - left, 1);
      }
    }
  }

  paint(polygon, rect);
  const rows = pixels.map(pixelSpans);
  return { width, height, colors, pixels, rows, lift, grandScale };
}

function pixelSpans(row) {
  const spans = [];
  for (let start = 0; start < row.length;) {
    let end = start + 1;
    while (end < row.length && row[end] === row[start]) end++;
    if (row[start]) spans.push([row[start], start, end]);
    start = end;
  }
  return spans;
}

