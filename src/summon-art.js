function indexedSummonArt(original, grid, materials) {
  const pixels = grid.map(row => Array.from(row, key => materials[key]?.[0] ?? null));
  return {
    ...original,
    width: grid[0].length,
    height: grid.length,
    colors: Object.fromEntries(Object.values(materials)),
    pixels,
    rows: pixels.map(pixelSpans),
  };
}

