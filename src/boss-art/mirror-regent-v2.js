const SHARD_ORBITS = Object.freeze([
  { key: 'shardLeftMid', phase: 0.0, rx: 2, ry: 4, dir: -1 },
  { key: 'shardLeftLow', phase: 1.4, rx: 2, ry: 3, dir: -1 },
  { key: 'shardRightMid', phase: 2.3, rx: 2, ry: 4, dir: 1 },
  { key: 'shardRightOuter', phase: 3.7, rx: 2, ry: 3, dir: 1 },
  { key: 'shardRightLow', phase: 5.0, rx: 2, ry: 3, dir: 1 },
]);

export const MIRROR_REGENT_V2_DEF = Object.freeze({
  grid: MIRROR_REGENT_V2_GRID,
  materials: MIRROR_REGENT_V2_MATERIALS,
  parts: MIRROR_REGENT_V2_SHARDS,
  animate({ frame = 0, pose = 'idle', progress = 0, attacking = false, charging = false, hurt = false, reducedMotion = false, colors }) {
    const rm = Boolean(reducedMotion);
    const flicker = !rm && (frame % 2 === 1);
    const reflecting = pose === 'reflect';
    const partStates = {};

    for (let i = 0; i < SHARD_ORBITS.length; i++) {
      const cfg = SHARD_ORBITS[i];
      if (rm) {
        partStates[cfg.key] = { frame: 0, dx: 0, dy: 0 };
        continue;
      }
      const ang = frame * 1.15 + cfg.phase;
      let dx = Math.round(Math.cos(ang) * cfg.rx);
      let dy = Math.round(Math.sin(ang) * cfg.ry);
      if (charging) {
        dx += cfg.dir * 2;
        dy -= 4;
      } else if (attacking) {
        const surge = Math.round(Math.sin(Math.min(1, progress) * Math.PI) * 6 + 2);
        dx += cfg.dir < 0 ? -surge : Math.round(surge * 0.35);
        dy -= cfg.dir < 0 ? 2 : 1;
      }
      const fIdx = (frame + i) % 4;
      partStates[cfg.key] = { frame: fIdx, dx, dy };
    }

    let materialOverrides = null;
    if (reflecting || charging || attacking) {
      materialOverrides = {
        cyanMid: colors.cyanBright,
        cyanBright: colors.cyanGlow,
        cyanGlow: colors.core,
        core: colors.coreWhite,
        icePale: colors.frostLight,
        ...(reflecting ? {
          silverMid: colors.silverLight,
          silverLight: colors.whiteFrost,
          lavenderMid: colors.lavenderPale,
        } : {}),
      };
    } else if (hurt && !rm) {
      materialOverrides = {
        cyanBright: colors.coreWhite,
        core: colors.coreWhite,
      };
    } else if (flicker) {
      materialOverrides = {
        cyanMid: colors.cyanBright,
        cyanBright: colors.cyanGlow,
        core: colors.coreWhite,
      };
    }

    const effects = [{ type: 'groundShadow', rx: 20, ry: 3, colorIndex: 0 }];
    if (!rm && charging) {
      effects.push({
        type: 'orbitDiamonds',
        anchors: ['weapon', 'chest'],
        count: 3,
        rx: 10,
        ry: 6,
        offsetY: -2,
        speed: 230,
        color: '#9ceeff',
        coreColor: '#ffffff',
      });
    } else if (!rm && (attacking || reflecting)) {
      effects.push({
        type: 'anchorBolt',
        anchor: 'weapon',
        dx1: -6,
        dy1: -8,
        dx2: 6,
        dy2: 8,
        color: '#9ceeff',
        coreColor: '#ffffff',
      });
    }

    return { materialOverrides, partStates, effects };
  },
});
