export const VOLCANO_COLOSSUS_V2_DEF = Object.freeze({
  grid: VOLCANO_COLOSSUS_V2_GRID,
  materials: VOLCANO_COLOSSUS_V2_MATERIALS,
  parts: VOLCANO_COLOSSUS_V2_PARTS,
  animate({ frame = 0, progress = 0, attacking = false, charging = false, hurt = false, reducedMotion = false, armor = null, colors }) {
    const rm = Boolean(reducedMotion);
    const flicker = !rm && (frame % 2 === 1);
    const f = rm ? 0 : (frame % 4);
    const fastF = rm ? 0 : ((frame * 2) % 4);
    const cooled = armor === 0;

    const heaveDy = rm ? 0 : (charging ? 1 : (f === 1 || f === 2 ? -1 : 0));
    const headDx = rm ? 0 : (charging ? 1 : 0);

    const partStates = {
      smokePlumes: { visible: !rm, frame: f, dx: 0, dy: 0 },
      headJaw: { frame: rm ? 0 : (attacking ? 2 : (charging ? 2 : f)), dx: headDx, dy: heaveDy },
      volcanoCore: { frame: rm ? 0 : (charging || attacking ? fastF : f), dx: 0, dy: 0 },
      dorsalPlates: { frame: rm ? 0 : f, dx: 0, dy: heaveDy },
      leftForeleg: { frame: rm ? 0 : (charging ? 2 : f), dx: 0, dy: 0 },
      rightForeleg: { frame: rm ? 0 : (charging ? 2 : f), dx: 0, dy: 0 },
      hindLegs: { frame: rm ? 0 : (charging ? 2 : f), dx: 0, dy: 0 },
      tail: { frame: rm ? 0 : ((f + 1) % 4), dx: 0, dy: 0 },
      magmaChannels: { frame: rm ? 0 : (charging || attacking ? fastF : f), dx: 0, dy: 0 },
    };

    let materialOverrides = null;
    if (cooled && !charging && !attacking) {
      materialOverrides = {
        magmaMid: colors.magmaDark,
        magmaBright: colors.magmaMid,
        magmaGold: colors.magmaBright,
        magmaWhiteHot: colors.magmaGold,
      };
    } else if (charging || attacking) {
      materialOverrides = {
        magmaDark: colors.magmaMid,
        magmaMid: colors.magmaBright,
        magmaBright: colors.magmaGold,
        magmaGold: colors.magmaWhiteHot,
        magmaWhiteHot: colors.craterCore,
        craterCore: colors.coreWhite,
      };
    } else if (hurt && !rm) {
      materialOverrides = {
        magmaBright: colors.coreWhite,
        craterCore: colors.coreWhite,
      };
    } else if (flicker) {
      materialOverrides = {
        magmaBright: colors.magmaGold,
        craterCore: colors.coreWhite,
      };
    }

    const effects = [{ type: 'groundShadow', rx: 48, ry: 4, colorIndex: 0 }];
    if (!rm && (charging || f % 2 === 0)) {
      effects.push({
        type: 'orbitDiamonds',
        anchors: ['craterA', 'craterB', 'craterC'],
        count: charging ? 3 : 1,
        rx: 7,
        ry: 5,
        offsetY: -5,
        speed: charging ? 190 : 320,
        color: '#ff8524',
        coreColor: '#fffac2',
      });
    }
    if (!rm && attacking) {
      effects.push({
        type: 'anchorBolt',
        anchor: 'jaw',
        dx1: -2,
        dy1: 0,
        dx2: -28,
        dy2: 6,
        color: '#ff8524',
        coreColor: '#fffac2',
      });
    }

    return { materialOverrides, partStates, effects };
  },
});
