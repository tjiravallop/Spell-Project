export const LOOM_SOVEREIGN_V2_DEF = Object.freeze({
  grid: LOOM_SOVEREIGN_V2_GRID,
  materials: LOOM_SOVEREIGN_V2_MATERIALS,
  parts: LOOM_SOVEREIGN_V2_PARTS,
  animate({ frame = 0, progress = 0, attacking = false, charging = false, hurt = false, reducedMotion = false, colors }) {
    const rm = Boolean(reducedMotion);
    const flicker = !rm && (frame % 2 === 1);
    const f4 = rm ? 0 : (frame % 4);
    const f8 = rm ? 0 : (frame % 8);
    const fastF8 = rm ? 0 : ((frame * 2) % 8);
    const f6 = rm ? 0 : (frame % 6);
    const fastF6 = rm ? 0 : ((frame * 2) % 6);

    const ornDyL = rm ? 0 : Math.round(Math.sin(frame * 1.2) * 2);
    const ornDyR = rm ? 0 : Math.round(Math.sin(frame * 1.2 + 2.1) * 2);
    const spoolPull = rm ? 0 : (charging ? 2 : attacking ? -3 : 0);
    const spoolPullR = spoolPull ? -spoolPull : 0;
    const tendrilDx = rm ? 0 : (charging ? 2 : attacking ? -4 : 0);
    const tendrilDxR = tendrilDx ? -tendrilDx : 0;

    const partStates = {
      centralVoidEye: { frame: rm ? 0 : (charging || attacking ? 2 : f4), dx: 0, dy: 0 },
      innerWeavingRingA: { frame: rm ? 0 : (charging ? fastF8 : f8), dx: 0, dy: 0 },
      innerWeavingRingB: { frame: rm ? 0 : (charging ? (fastF8 + 3) % 8 : (f8 + 2) % 8), dx: 0, dy: 0 },
      leftSpool: { frame: rm ? 0 : (charging ? fastF6 : f6), dx: spoolPull, dy: 0 },
      rightSpool: { frame: rm ? 0 : ((charging ? fastF6 : f6) + 3) % 6, dx: spoolPullR, dy: 0 },
      leftOrnament: { frame: rm ? 0 : f4, dx: 0, dy: ornDyL },
      rightOrnament: { frame: rm ? 0 : (f4 + 2) % 4, dx: 0, dy: ornDyR },
      centralTapestry: { frame: rm ? 0 : (charging ? 2 : f4), dx: 0, dy: 0 },
      leftTextileTendrils: { frame: rm ? 0 : f4, dx: tendrilDx, dy: 0 },
      rightTextileTendrils: { frame: rm ? 0 : (f4 + 1) % 4, dx: tendrilDxR, dy: 0 },
    };

    let materialOverrides = null;
    if (charging || attacking) {
      materialOverrides = {
        magenta: colors.magentaBright,
        magentaBright: colors.core,
        thread: colors.threadBright,
        threadBright: colors.coreWhite,
        core: colors.coreWhite,
      };
    } else if (hurt && !rm) {
      materialOverrides = {
        magentaBright: colors.coreWhite,
        core: colors.coreWhite,
      };
    } else if (flicker) {
      materialOverrides = {
        magenta: colors.magentaBright,
        thread: colors.threadBright,
        core: colors.coreWhite,
      };
    }

    const sag = rm ? 4 : (charging ? 1 : attacking ? 0 : 4 + Math.round(Math.sin(frame * 1.4) * 2));
    const effects = [
      { type: 'groundShadow', rx: 24, ry: 3, colorIndex: 0 },
      { type: 'fateThread', from: 'leftSpool', to: 'chest', dx1: spoolPull, dy1: 0, dx2: 0, dy2: 0, sag, color: '#d982ff', pulseColor: '#ffe0ff', phase: frame },
      { type: 'fateThread', from: 'rightSpool', to: 'chest', dx1: spoolPullR, dy1: 0, dx2: 0, dy2: 0, sag, color: '#d982ff', pulseColor: '#ffe0ff', phase: frame + 1 },
      { type: 'fateThread', from: 'leftOrnament', to: 'leftSpool', dx1: 0, dy1: ornDyL, dx2: spoolPull, dy2: 0, sag: Math.max(0, sag - 1), color: '#f7bfff', pulseColor: '#ffffff', phase: frame + 2 },
      { type: 'fateThread', from: 'rightOrnament', to: 'rightSpool', dx1: 0, dy1: ornDyR, dx2: spoolPullR, dy2: 0, sag: Math.max(0, sag - 1), color: '#f7bfff', pulseColor: '#ffffff', phase: frame + 3 },
      { type: 'fateThread', from: 'chest', to: 'tapestry', dx1: 0, dy1: 0, dx2: 0, dy2: 0, sag: 0, color: '#d982ff', pulseColor: '#ffffff', phase: frame },
    ];
    if (!rm && charging) {
      effects.push({
        type: 'orbitDiamonds',
        anchors: ['eye', 'leftSpool', 'rightSpool'],
        count: 3,
        rx: 9,
        ry: 6,
        offsetY: 0,
        speed: 220,
        color: '#fa73e8',
        coreColor: '#ffffff',
      });
    } else if (!rm && attacking) {
      effects.push({
        type: 'anchorBolt',
        anchor: 'eye',
        dx1: -4,
        dy1: -4,
        dx2: -24,
        dy2: 10,
        color: '#fa73e8',
        coreColor: '#ffffff',
      });
    }

    return { materialOverrides, partStates, effects };
  },
});
