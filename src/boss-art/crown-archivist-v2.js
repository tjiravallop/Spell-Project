export const CROWN_ARCHIVIST_V2_DEF = Object.freeze({
  grid: CROWN_ARCHIVIST_V2_GRID,
  materials: CROWN_ARCHIVIST_V2_MATERIALS,
  parts: Object.freeze({
    leftGrimoire: Object.freeze({
      anchor: CROWN_ARCHIVIST_V2_LEFT_GRIMOIRE.anchor,
      z: 'front',
      grid: CROWN_ARCHIVIST_V2_LEFT_GRIMOIRE.grid,
    }),
    rightGrimoire: Object.freeze({
      anchor: CROWN_ARCHIVIST_V2_RIGHT_GRIMOIRE.anchor,
      z: 'front',
      grid: CROWN_ARCHIVIST_V2_RIGHT_GRIMOIRE.grid,
    }),
  }),
  animate({ frame = 0, progress = 0, attacking = false, charging = false, reducedMotion = false, colors }) {
    const rm = Boolean(reducedMotion);
    const flicker = !rm && (frame % 2 === 1);
    const phase = frame * 1.1;
    const leftIdleDy = rm ? 0 : Math.round(Math.sin(phase) * 4);
    const leftIdleDx = rm ? 0 : Math.round(Math.cos(phase * 0.7) * 1);
    const rightIdleDy = rm ? 0 : Math.round(Math.sin(phase + Math.PI * 0.65) * 4);
    const rightIdleDx = rm ? 0 : Math.round(Math.cos(phase * 0.7 + 1.4) * 1);
    const atkAdvance = rm ? 0 : (attacking ? -Math.round(Math.sin(Math.min(1, progress) * Math.PI) * 7 + 2) : 0);
    const chgLift = rm ? 0 : (charging ? -5 : 0);

    const partStates = {
      leftGrimoire: {
        dx: attacking ? atkAdvance : leftIdleDx,
        dy: charging ? chgLift : (attacking ? -2 : leftIdleDy),
      },
      rightGrimoire: {
        dx: attacking ? Math.round(atkAdvance * 0.7) : rightIdleDx,
        dy: charging ? (rm ? 0 : chgLift - 1) : (attacking ? (rm ? 0 : -1) : rightIdleDy),
      },
    };

    const materialOverrides = (flicker || attacking || charging) ? {
      runeDark: (attacking || charging) ? colors.runeMid : colors.runeDark,
      runeMid: (attacking || charging) ? colors.runeBright : (flicker ? '#34d2c7' : colors.runeMid),
      runeBright: (attacking || charging) ? colors.core : (flicker ? '#79fff2' : colors.runeBright),
      core: (attacking || charging) ? colors.coreWhite : (flicker ? '#c8fff9' : colors.core),
      ...(attacking || charging ? {
        pageMid: colors.pageLight,
        pageLight: '#fffaf3',
      } : {}),
    } : null;

    const effects = (!rm && charging) ? [
      { type: 'orbitDiamonds', anchors: ['weapon', 'rightBook'], count: 3, rx: 11, ry: 7, offsetY: -4, speed: 240, color: '#52ebde', coreColor: '#dcfffb' },
    ] : [];

    return { materialOverrides, partStates, effects };
  },
});
